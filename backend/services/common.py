"""Small shared helpers for IDs, provenance metadata and severity maths."""

from __future__ import annotations

import uuid
from datetime import datetime, timezone

from models.schemas import EngineMeta, EngineMode, Severity

SEVERITY_ORDER: dict[Severity, int] = {
    Severity.LOW: 0,
    Severity.MEDIUM: 1,
    Severity.HIGH: 2,
    Severity.CRITICAL: 3,
}


def new_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:16]}"


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


def worst_severity(*severities: Severity) -> Severity:
    return max(severities, key=lambda s: SEVERITY_ORDER[s])


def severity_at_least(value: Severity, threshold: Severity) -> bool:
    return SEVERITY_ORDER[value] >= SEVERITY_ORDER[threshold]


HEURISTIC_DISCLOSURE = (
    "Produced by the offline deterministic vision engine (no multimodal LLM key configured). "
    "Metrics are derived from colour-distribution, edge-density and ridge-linearity analysis of the "
    "uploaded frame. Treat as a triage/screening aid, not a certified inspection."
)


def make_engine_meta(
    *,
    mode: EngineMode,
    provider: str,
    model: str,
    latency_ms: int,
    confidence: float,
    request_id: str,
    disclosure: str,
) -> EngineMeta:
    return EngineMeta(
        engine_mode=mode,
        provider=provider,
        model=model,
        latency_ms=max(0, latency_ms),
        generated_at=utcnow(),
        request_id=request_id,
        confidence=round(clamp(confidence, 0.0, 1.0), 3),
        disclosure=disclosure,
    )


